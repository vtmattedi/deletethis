"""Offline analysis of recorded INMP441 audio.

Examples:

    python tools/audio/analyze.py
    python tools/audio/analyze.py --plots
    python tools/audio/analyze.py --plots --csv features.csv
    python tools/audio/analyze.py --nfft 4096

Recording names encode two concepts:

    off_01.wav
        state=off
        interference=clean

    fan_talking_01.wav
        state=fan
        interference=talking

    compressor_talking_02.wav
        state=compressor
        interference=talking

Timestamp prefixes generated by capture.py and trailing numeric indexes
are ignored.

The goal is to find features that distinguish:

    OFF / FAN / COMPRESSOR

while remaining stable when interference such as speech is added.
"""

from __future__ import annotations

import argparse
import csv
import re
import sys
from dataclasses import dataclass
from pathlib import Path

import numpy as np
from scipy.io import wavfile
from scipy.signal import spectrogram


HERE = Path(__file__).resolve().parent
DEFAULT_RECORDINGS = HERE / "recordings"
DEFAULT_PLOTDIR = HERE / "plots"

DEFAULT_SAMPLE_RATE = 16000
DEFAULT_NFFT = 1024

DB_FLOOR = -120.0

PEAK_MIN_HZ = 100.0
PEAK_MAX_HZ = 4000.0

STATE_ORDER = ["off", "fan", "compressor"]
KNOWN_STATES = set(STATE_ORDER)

DATE_PATTERN = re.compile(r"^\d{4}-\d{2}-\d{2}$")
NUMBER_PATTERN = re.compile(r"^\d+$")


# ---------------------------------------------------------------------
# Spectral features
# ---------------------------------------------------------------------

# Original exploratory bands.
BANDS: list[tuple[str, float, float]] = [
    ("30-80", 30.0, 80.0),
    ("80-200", 80.0, 200.0),
    ("200-500", 200.0, 500.0),
    ("500-1k", 500.0, 1000.0),
    ("1k-2k", 1000.0, 2000.0),
    ("2k-4k", 2000.0, 4000.0),
    ("1100-1200", 1100.0, 1200.0),

    # Derived classifier-oriented bands.
    ("200-1200", 200.0, 1200.0),
    ("1500-4000", 1500.0, 4000.0),
]

# high/mech is expressed in dB:
#
#     1500-4000 dB - 200-1200 dB
#
# This is equivalent to a spectral power ratio in logarithmic form.
DERIVED_FEATURES = [
    "high/mech",
]

FEATURES = (
    ["RMS"]
    + [name for name, _, _ in BANDS]
    + DERIVED_FEATURES
)


# ---------------------------------------------------------------------
# Naming / labels
# ---------------------------------------------------------------------

@dataclass(frozen=True)
class Labels:
    state: str
    interference: str

    @property
    def condition(self) -> str:
        if self.interference == "clean":
            return self.state

        return f"{self.state}_{self.interference}"


def infer_labels(path: Path) -> Labels:
    tokens = []

    for token in path.stem.lower().split("_"):
        if not token:
            continue

        if DATE_PATTERN.match(token):
            continue

        if NUMBER_PATTERN.match(token):
            continue

        tokens.append(token)

    state_index = None

    for index, token in enumerate(tokens):
        if token in KNOWN_STATES:
            state_index = index
            break

    if state_index is None:
        return Labels(
            state="unknown",
            interference="_".join(tokens) or "unknown",
        )

    state = tokens[state_index]

    remainder = (
        tokens[:state_index]
        + tokens[state_index + 1 :]
    )

    interference = (
        "_".join(remainder)
        if remainder
        else "clean"
    )

    return Labels(
        state=state,
        interference=interference,
    )


# ---------------------------------------------------------------------
# Signal helpers
# ---------------------------------------------------------------------

def to_float(samples: np.ndarray) -> np.ndarray:
    """Normalize WAV samples to approximately [-1, 1)."""

    if samples.ndim > 1:
        samples = samples[:, 0]

    if np.issubdtype(samples.dtype, np.floating):
        return samples.astype(np.float64)

    info = np.iinfo(samples.dtype)

    if info.min == 0:
        midpoint = (info.max + 1) / 2.0

        return (
            samples.astype(np.float64) - midpoint
        ) / midpoint

    return (
        samples.astype(np.float64)
        / float(-info.min)
    )


def power_to_db(
    power: np.ndarray | float,
) -> np.ndarray | float:
    """Mean-square power -> dBFS."""

    amplitude = np.sqrt(
        np.maximum(power, 0.0)
    )

    return np.maximum(
        20.0
        * np.log10(
            np.maximum(amplitude, 1e-12)
        ),
        DB_FLOOR,
    )


def frame_signal(
    signal: np.ndarray,
    nperseg: int,
    noverlap: int,
) -> np.ndarray:
    """Create windows aligned with scipy.signal.spectrogram."""

    step = nperseg - noverlap

    count = (
        1
        + (signal.size - nperseg) // step
    )

    offsets = (
        step
        * np.arange(count)[:, None]
    )

    indexes = (
        offsets
        + np.arange(nperseg)[None, :]
    )

    return signal[indexes]


# ---------------------------------------------------------------------
# Analysis object
# ---------------------------------------------------------------------

@dataclass
class Analysis:
    path: Path

    state: str
    interference: str

    sample_rate: int
    duration: float

    times: np.ndarray
    freqs: np.ndarray
    power: np.ndarray

    rms_db: np.ndarray
    band_db: dict[str, np.ndarray]

    peak_hz: np.ndarray

    @property
    def condition(self) -> str:
        if self.interference == "clean":
            return self.state

        return (
            f"{self.state}_"
            f"{self.interference}"
        )

    def feature(self, name: str) -> np.ndarray:
        if name == "RMS":
            return self.rms_db

        if name == "high/mech":
            return (
                self.band_db["1500-4000"]
                - self.band_db["200-1200"]
            )

        return self.band_db[name]

    @property
    def mean_spectrum_db(self) -> np.ndarray:
        return power_to_db(
            self.power.mean(axis=1)
        )


# ---------------------------------------------------------------------
# Per-file analysis
# ---------------------------------------------------------------------

def analyse_file(
    path: Path,
    nfft: int,
    overlap: float,
) -> Analysis:

    sample_rate, raw = wavfile.read(path)

    signal = to_float(raw)

    if signal.size < nfft:
        raise ValueError(
            f"{path.name}: only "
            f"{signal.size} samples; "
            f"need at least {nfft}"
        )

    labels = infer_labels(path)

    # Remove recording-wide DC.
    signal = signal - signal.mean()

    noverlap = int(
        nfft * overlap
    )

    freqs, times, power = spectrogram(
        signal,
        fs=sample_rate,
        window="hamming",
        nperseg=nfft,
        noverlap=noverlap,
        detrend="constant",
        scaling="spectrum",
        mode="psd",
    )

    # ----------------------------------------------------------
    # True time-domain RMS.
    # ----------------------------------------------------------

    windows = frame_signal(
        signal,
        nfft,
        noverlap,
    )

    windows = (
        windows
        - windows.mean(
            axis=1,
            keepdims=True,
        )
    )

    rms_db = power_to_db(
        np.mean(
            windows * windows,
            axis=1,
        )
    )

    if rms_db.size != times.size:
        raise ValueError(
            f"{path.name}: framing mismatch: "
            f"{rms_db.size} RMS windows vs "
            f"{times.size} spectral windows"
        )

    # ----------------------------------------------------------
    # Spectral band power.
    # ----------------------------------------------------------

    band_db: dict[
        str,
        np.ndarray
    ] = {}

    for name, low, high in BANDS:
        mask = (
            (freqs >= low)
            & (freqs < high)
        )

        if not mask.any():
            band_db[name] = np.full(
                times.shape,
                DB_FLOOR,
            )

            continue

        band_power = power[
            mask,
            :
        ].sum(axis=0)

        band_db[name] = power_to_db(
            band_power
        )

    # ----------------------------------------------------------
    # Dominant peak.
    # ----------------------------------------------------------

    peak_mask = (
        (freqs >= PEAK_MIN_HZ)
        & (freqs <= PEAK_MAX_HZ)
    )

    peak_freqs = freqs[peak_mask]

    if peak_freqs.size:
        peak_indexes = np.argmax(
            power[peak_mask, :],
            axis=0,
        )

        peak_hz = peak_freqs[
            peak_indexes
        ]
    else:
        peak_hz = np.zeros(
            times.shape
        )

    return Analysis(
        path=path,

        state=labels.state,
        interference=labels.interference,

        sample_rate=sample_rate,
        duration=(
            signal.size
            / sample_rate
        ),

        times=times,
        freqs=freqs,
        power=power,

        rms_db=rms_db,
        band_db=band_db,

        peak_hz=peak_hz,
    )


# ---------------------------------------------------------------------
# Grouping
# ---------------------------------------------------------------------

def state_sort_key(
    state: str,
) -> tuple[int, str]:

    if state in STATE_ORDER:
        return (
            STATE_ORDER.index(state),
            state,
        )

    return (
        len(STATE_ORDER),
        state,
    )


def group_by_state(
    analyses: list[Analysis],
) -> dict[str, list[Analysis]]:

    grouped: dict[
        str,
        list[Analysis]
    ] = {}

    for analysis in analyses:
        grouped.setdefault(
            analysis.state,
            [],
        ).append(analysis)

    return dict(
        sorted(
            grouped.items(),
            key=lambda item:
                state_sort_key(item[0]),
        )
    )


def group_by_condition(
    analyses: list[Analysis],
) -> dict[str, list[Analysis]]:

    grouped: dict[
        str,
        list[Analysis]
    ] = {}

    for analysis in analyses:
        grouped.setdefault(
            analysis.condition,
            [],
        ).append(analysis)

    return grouped


# ---------------------------------------------------------------------
# Generic feature access
# ---------------------------------------------------------------------

def concatenate_feature(
    analyses: list[Analysis],
    feature: str,
) -> np.ndarray:

    return np.concatenate(
        [
            analysis.feature(feature)
            for analysis in analyses
        ]
    )


# ---------------------------------------------------------------------
# Tables
# ---------------------------------------------------------------------

def format_table(
    rows: list[list[str]],
    headers: list[str],
) -> str:

    widths = [
        len(header)
        for header in headers
    ]

    for row in rows:
        for index, cell in enumerate(row):
            widths[index] = max(
                widths[index],
                len(cell),
            )

    def render(
        cells: list[str],
    ) -> str:

        return "  ".join(
            (
                cell.ljust(
                    widths[index]
                )
                if index == 0
                else cell.rjust(
                    widths[index]
                )
            )
            for index, cell
            in enumerate(cells)
        )

    lines = [
        render(headers),
        "  ".join(
            "-" * width
            for width in widths
        ),
    ]

    lines.extend(
        render(row)
        for row in rows
    )

    return "\n".join(lines)


