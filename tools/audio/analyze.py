def make_plots(
    grouped_states: dict[
        str,
        list[Analysis],
    ],
    analyses: list[Analysis],
    plotdir: Path,
    fmax: float,
) -> list[Path]:

    import matplotlib

    matplotlib.use("Agg")

    import matplotlib.pyplot as plt

    plotdir.mkdir(
        parents=True,
        exist_ok=True,
    )

    written: list[Path] = []

    # ----------------------------------------------------------
    # Average spectrum by physical state, including interference.
    # ----------------------------------------------------------

    figure, axis = plt.subplots(
        figsize=(11, 6)
    )

    for state, state_analyses in grouped_states.items():
        freqs = state_analyses[0].freqs

        spectra = [
            a.power.mean(axis=1)
            for a in state_analyses
        ]

        mean_power = np.mean(
            spectra,
            axis=0,
        )

        axis.plot(
            freqs,
            power_to_db(mean_power),
            linewidth=1.0,
            label=state,
        )

    axis.set_xlim(
        0,
        fmax,
    )

    axis.set_xlabel("Hz")
    axis.set_ylabel("dBFS")

    axis.set_title(
        "Average spectrum by physical AC state"
    )

    axis.grid(alpha=0.3)
    axis.legend()

    path = (
        plotdir
        / "spectrum_by_state.png"
    )

    figure.savefig(
        path,
        dpi=130,
        bbox_inches="tight",
    )

    plt.close(figure)
    written.append(path)

    # ----------------------------------------------------------
    # Per-file plots.
    # ----------------------------------------------------------

    for analysis in analyses:
        written.append(
            _plot_bands_over_time(
                plt,
                analysis,
                plotdir,
            )
        )

        written.append(
            _plot_spectrogram(
                plt,
                analysis,
                plotdir,
                fmax,
            )
        )

    return written


def _plot_bands_over_time(
    plt,
    analysis: Analysis,
    plotdir: Path,
) -> Path:

    figure, axis = plt.subplots(
        figsize=(11, 5)
    )

    axis.plot(
        analysis.times,
        analysis.rms_db,
        linewidth=1.4,
        label="RMS",
    )

    for feature in [
        "30-80",
        "200-1200",
        "500-1k",
        "1k-2k",
        "1500-4000",
    ]:
        axis.plot(
            analysis.times,
            analysis.feature(feature),
            linewidth=0.8,
            label=feature,
        )

    axis.set_xlabel("s")
    axis.set_ylabel("dBFS")

    axis.set_title(
        f"Features over time - "
        f"{analysis.path.name}"
    )

    axis.grid(alpha=0.3)

    axis.legend(
        ncol=3,
        fontsize=8,
    )

    path = (
        plotdir
        / f"bands_{analysis.path.stem}.png"
    )

    figure.savefig(
        path,
        dpi=130,
        bbox_inches="tight",
    )

    plt.close(figure)

    return path


def _plot_spectrogram(
    plt,
    analysis: Analysis,
    plotdir: Path,
    fmax: float,
) -> Path:

    figure, axis = plt.subplots(
        figsize=(11, 5)
    )

    mesh = axis.pcolormesh(
        analysis.times,
        analysis.freqs,
        power_to_db(
            analysis.power
        ),
        shading="auto",
        vmin=DB_FLOOR,
        vmax=-20.0,
    )

    axis.set_ylim(
        0,
        fmax,
    )

    axis.set_xlabel("s")
    axis.set_ylabel("Hz")

    axis.set_title(
        f"Spectrogram - "
        f"{analysis.path.name}"
    )

    figure.colorbar(
        mesh,
        ax=axis,
        label="dBFS",
        pad=0.01,
    )

    path = (
        plotdir
        / f"spectrogram_"
        f"{analysis.path.stem}.png"
    )

    figure.savefig(
        path,
        dpi=130,
        bbox_inches="tight",
    )

    plt.close(figure)

    return path


