def build_parser() -> argparse.ArgumentParser:

    parser = argparse.ArgumentParser(
        description=(
            "Compare OFF/FAN/COMPRESSOR "
            "audio signatures while treating "
            "speech and other interference "
            "separately."
        )
    )

    parser.add_argument(
        "files",
        nargs="*",
        type=Path,
        help=(
            "WAV files or directories. "
            "Default: tools/audio/recordings"
        ),
    )

    parser.add_argument(
        "--nfft",
        type=int,
        default=DEFAULT_NFFT,
        help=(
            f"FFT/window size "
            f"(default: {DEFAULT_NFFT})"
        ),
    )

    parser.add_argument(
        "--overlap",
        type=float,
        default=0.5,
        help=(
            "Window overlap fraction "
            "(default: 0.5)"
        ),
    )

    parser.add_argument(
        "--stability-seconds",
        type=float,
        default=2.0,
        help=(
            "Window used for temporal "
            "stability analysis "
            "(default: 2.0 s)"
        ),
    )

    parser.add_argument(
        "--fmax",
        type=float,
        default=None,
        help=(
            "Highest plotted frequency "
            "(default: Nyquist)"
        ),
    )

    parser.add_argument(
        "--plots",
        action="store_true",
        help="Write PNG plots",
    )

    parser.add_argument(
        "--plotdir",
        type=Path,
        default=DEFAULT_PLOTDIR,
        help=(
            "Plot output directory "
            "(default: tools/audio/plots)"
        ),
    )

    parser.add_argument(
        "--csv",
        type=Path,
        default=None,
        help=(
            "Write per-window features "
            "to CSV"
        ),
    )

    return parser


def collect_files(
    args: argparse.Namespace,
) -> list[Path]:

    if args.files:
        paths: list[Path] = []

        for entry in args.files:
            if entry.is_dir():
                paths.extend(
                    sorted(
                        entry.glob("*.wav")
                    )
                )
            else:
                paths.append(entry)

        return paths

    return sorted(
        DEFAULT_RECORDINGS.glob(
            "*.wav"
        )
    )


# ---------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------

def main(
    argv: list[str] | None = None,
) -> int:

    parser = build_parser()

    args = parser.parse_args(
        argv
    )

    if (
        args.nfft < 64
        or args.nfft
        & (args.nfft - 1)
    ):
        parser.error(
            "--nfft must be a power "
            "of two and at least 64"
        )

    if not (
        0.0
        <= args.overlap
        < 1.0
    ):
        parser.error(
            "--overlap must be in [0, 1)"
        )

    if args.stability_seconds <= 0:
        parser.error(
            "--stability-seconds "
            "must be > 0"
        )

    paths = collect_files(args)

    if not paths:
        print(
            f"No recordings found in "
            f"{DEFAULT_RECORDINGS}.\n\n"
            "Capture one with:\n"
            "  python "
            "tools/audio/capture.py "
            "COM9 --label off_01 "
            "--seconds 30",
            file=sys.stderr,
        )

        return 1

    analyses: list[Analysis] = []

    for path in paths:
        if not path.exists():
            print(
                f"warning: "
                f"{path} does not exist",
                file=sys.stderr,
            )

            continue

        try:
            analyses.append(
                analyse_file(
                    path,
                    args.nfft,
                    args.overlap,
                )
            )

        except (
            ValueError,
            OSError,
        ) as error:

            print(
                f"warning: {error}",
                file=sys.stderr,
            )

    if not analyses:
        print(
            "error: nothing could "
            "be analysed",
            file=sys.stderr,
        )

        return 1

    sample_rates = {
        a.sample_rate
        for a in analyses
    }

    if len(sample_rates) > 1:
        print(
            "warning: mixed sample rates: "
            f"{sorted(sample_rates)}",
            file=sys.stderr,
        )

    sample_rate = (
        analyses[0].sample_rate
    )

    fmax = (
        args.fmax
        or sample_rate / 2.0
    )

    resolution = (
        sample_rate
        / args.nfft
    )

    print()
    print(
        f"{len(analyses)} recording(s)   "
        f"{sample_rate} Hz   "
        f"N={args.nfft} "
        f"({resolution:.2f} Hz/bin, "
        f"{args.nfft / sample_rate * 1000:.0f} ms/window)   "
        f"Hamming   "
        f"overlap {args.overlap:.0%}"
    )

    print()
    print("Per file")
    print()
    print(
        per_file_table(
            analyses
        )
    )

    grouped_conditions = (
        group_by_condition(
            analyses
        )
    )

    print()
    print(
        "Per condition"
    )
    print(
        "(physical state + interference)"
    )
    print()
    print(
        condition_table(
            grouped_conditions
        )
    )

    grouped_states = (
        group_by_state(
            analyses
        )
    )

    print()
    print(
        "Physical-state separation"
    )
    print(
        "All interference variants are "
        "included in each OFF/FAN/"
        "COMPRESSOR population."
    )
    print(
        "Positive P10/P90 margin = "
        "robust non-overlap."
    )
    print()
    print(
        state_margin_table(
            grouped_states
        )
    )

    print()
    print(
        "Interference invariance"
    )
    print(
        "Smaller absolute shift is better."
    )
    print()
    print(
        interference_shift_table(
            analyses
        )
    )

    print()
    print(
        "Temporal stability"
    )
    print(
        "Lower rolling standard deviation "
        "means a more stationary feature."
    )
    print()
    print(
        stability_table(
            analyses,
            args.stability_seconds,
        )
    )

    if args.csv:
        write_csv(
            args.csv,
            analyses,
        )

        print()
        print(
            f"Wrote per-window "
            f"features to {args.csv}"
        )

    if args.plots:
        written = make_plots(
            grouped_states,
            analyses,
            args.plotdir,
            fmax,
        )

        print()
        print(
            f"Wrote {len(written)} "
            f"plot(s) to "
            f"{args.plotdir}"
        )

    print()

    return 0


if __name__ == "__main__":
    raise SystemExit(
        main()
    )